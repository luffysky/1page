-- 把 _migrations 關起來
--
-- 這張表是遷移紀錄簿，不是產品資料，所以它從來沒有被想過要不要開 RLS——
-- 而 PostgREST 會把 public schema 的**每一張表**都變成一個端點。
--
-- 實測：匿名帶 anon key 打 /rest/v1/_migrations 回 200，
-- 內容是每一個 migration 的檔名與套用時間，例如
--   20260811000004_admin_roles.sql
--   20260812000006_leads.sql
--   20260813000007_saved_sites.sql
--
-- 那等於把整個資料庫的演進史、有哪些表、做了哪些功能，一次交出去。
-- 單獨看不是漏洞，但它讓所有其他攻擊都變得比較好猜。
--
-- ⚠️ 這是「宣告了一個東西卻沒有人在看它」的另一種形態：
-- 不是我們寫了沒用到，是**遷移工具自己建的表**，
-- 沒有任何一條檢查在問「public schema 裡是不是每張表都關好了」。
-- audit:wiring 因此新增一項。
--
-- 不加任何 policy：service_role 走的是 bypass RLS，不受影響；
-- anon 與 authenticated 沒有 policy 就是一列都讀不到。
-- ============================================================================

alter table _migrations enable row level security;
