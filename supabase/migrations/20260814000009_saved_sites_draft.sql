-- ============================================================================
-- saved_sites 改存「輸入」而不是「成品」
--
-- ── 為什麼要改 ─────────────────────────────────────────────────
--
-- 原本這張表存的是 buildSiteConfig() 算出來的整份 SiteConfig。存得進去，
-- 但**載不回編輯器**：成品裡沒有「你當初選的是哪一套模板、哪一組主題」，
-- 那些資訊在算出成品的那一刻就被丟掉了，而編輯器的狀態正是那幾個純量。
--
-- 換句話說 config 欄位從建立起就沒有任何讀取端——它是「宣告了一個東西，
-- 卻沒有任何地方用到它」的又一次（見 CLAUDE.md）。真正需要的是輸入。
--
-- 改存 draft 之後，資料庫與 sessionStorage 存的是**同一份文件、
-- 同一個 schema**（src/features/website-engine/editor-state.ts）。
-- 兩邊各存各的形狀，正是這次載不回來的原因。
--
-- ── 為什麼不兩個欄位都留 ───────────────────────────────────────
--
-- 「順便留一份成品快照給未來的發佈功能用」聽起來沒有壞處，
-- 但發佈功能還不存在，而沒有讀取端的欄位就是會慢慢過期的第二份真相。
-- 真的要凍結一份快照時，那件事本身會需要自己的設計（版本、發佈時間、
-- 回滾），不會是今天隨手多存的這一欄。
--
-- ── 相容性 ─────────────────────────────────────────────────────
--
-- 套用前實測 `select count(*) from saved_sites` 為 0，所以直接換欄位。
-- 若某個環境已經有資料，`add column ... not null` 會直接失敗——
-- 這是刻意的：舊資料**沒有辦法**轉成 draft（成品推不回輸入），
-- 讓它安靜地變成一堆載不開的草稿，比當場失敗更糟。
-- ============================================================================

alter table saved_sites
  drop column config,
  add column draft jsonb not null;

comment on column saved_sites.draft is
  '編輯器狀態（模板/主題/配色/品牌/產業/區塊覆寫）。形狀由 editor-state.ts 的 editorStateSchema 定義，讀出來一律再驗一次。';
