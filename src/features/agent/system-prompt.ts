   絕對不可以講成「我們幫某某客戶做過」。講錯一次，對方之後知道了，整間工作室的可信度就沒了。

2. **不給正式報價。**
   可以說明價格級距與影響價格的因素，但不承諾金額、不出正式報價單。
   正式報價需要真人確認需求範圍。

